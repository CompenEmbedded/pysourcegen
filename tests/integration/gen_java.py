"""Print a Java program that uses every class of the generator."""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'src'))

from pysourcegen import *  # noqa: E402,F403
f = JavaFile()
f.AddHead(JavaComment('Generated by pysourcegen'))
f.AddImport('java.util.List')
f.AddImport('java.lang.Math.max', static=True)

shape = JavaInterface('Shape', modifiers='')
shape.Add(JavaMethod('area', 'double', None, modifiers=''))
shape.Add(JavaMethod('name', 'String', JavaBody([JavaText('return "shape";')]), modifiers='default'))
f.Add(shape)

e = JavaEnum('Color', modifiers='')
e.AddConstant('RED', '"red"'); e.AddConstant('GREEN', '"green"')
e.AddField('String', 'label', modifiers='final')
ctor = JavaMethod('Color', None, JavaBody([JavaText('this.label = label;')]), modifiers='')
ctor.AddParameter('String', 'label')
e.Add(ctor)
f.Add(e)
simple = JavaEnum('Size', modifiers='')
simple.AddConstant('S'); simple.AddConstant('M')
f.Add(simple)

base = JavaClass('Base', modifiers='abstract')
base.Add(JavaMethod('hello', 'String', JavaBody([JavaText('return "base";')])))
f.Add(base)

sq = JavaClass('Square', modifiers='final', extends='Base', implements=['Shape', 'Comparable<Square>'])
sq.AddField('double', 'side')
sq.AddField('int', 'COUNT', '0', modifiers='static')
c2 = JavaMethod('Square', None, JavaBody([JavaText('this.side = side;'), JavaText('COUNT++;')]))
c2.AddParameter('double', 'side')
sq.Add(c2)
sq.Add(JavaDocComment('Area.\n\n@return the area'))
sq.Add(JavaAnnotation('Override'))
sq.Add(JavaMethod('area', 'double', JavaBody([JavaText('return side * side;')])))
sq.Add(JavaAnnotation('Override'))
cmp = JavaMethod('compareTo', 'int', JavaBody([JavaText('return Double.compare(side, o.side);')]))
cmp.AddParameter('Square', 'o')
sq.Add(cmp)
sq.Add(JavaMethod('nothing', 'void', JavaBody([]), modifiers='static', throws=['Exception']))
f.Add(sq)

sw = JavaSwitch('c', JavaBody([
    JavaSwitchCase('RED', [JavaText('return "r" + c.label;')], add_break=False),
    JavaSwitchCase('GREEN', JavaBody([JavaComment('falls out'), JavaText('n++;')])),
    JavaSwitchDefault([]),
]))
desc = JavaMethod('describe', 'String', JavaBody([JavaText('int n = 0;'), sw, JavaText('return "g" + n;')]), modifiers='static')
desc.AddParameter('Color', 'c')
main = JavaMethod('main', 'void', JavaBody([
    JavaText('Square s = new Square(3);'),
    JavaText('List<Square> l = List.of(s, new Square(1));'),
    JavaText('System.out.println(s.area() + " " + s.name() + " " + s.hello() + " " + describe(Color.RED) + " " + describe(Color.GREEN) + " " + max(1, 2) + " " + Size.M + " " + Square.COUNT + " " + l.size());'),
    JavaBody([JavaText('int unused = 0;')]),
]), modifiers='public static', throws='Exception')
main.AddParameter('String[]', 'args')
app = JavaClass('Main')
app.Add(desc); app.Add(main)
f.Add(app)
print(f, end='')
