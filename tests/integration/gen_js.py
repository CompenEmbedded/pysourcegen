"""Print a JavaScript (argument 'js') or TypeScript (argument 'ts') program that uses every class of the generator."""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'src'))

from pysourcegen import *  # noqa: E402,F403
ts = sys.argv[1] == 'ts'
T = (lambda t: t) if ts else (lambda t: None)

f = JsFile()
f.AddHead(JsComment('Generated by pysourcegen'))
f.AddImport('node:path', ['basename', 'join'])
f.AddImport('node:assert', default='assert')
f.AddImport('node:process')

if ts:
    e = JsEnum('Color', export=True)
    e.Add(JsDocComment('Primary'))
    e.AddMember('Red', 0); e.AddMember('Green')
    f.Add(e)
    i = JsInterface('Shape', export=True)
    i.AddMember('name', 'string'); i.AddMember('sides', 'number', optional=True)
    i.AddMember('area()', 'number')
    f.Add(i)

c = JsClass('Square', implements='Shape' if ts else None, export=True)
c.AddField('name', T('string'), '"square"')
c.AddField('count', T('number'), '0', modifiers='static')
ctor = JsMethod('constructor', None, JsBody([JsText('Square.count++;')] + ([] if ts else [JsText('this.side = side;')])))
ctor.AddParameter('side' if not ts else 'private side', T('number'), '1')
c.Add(ctor)
c.Add(JsDocComment('Area of the square.\n\n@returns the area'))
area = JsMethod('area', T('number'), JsBody([JsText('return this.side * this.side;')]))
c.Add(area)
c.Add(JsMethod('reset', T('void'), JsBody([]), modifiers='static'))
f.Add(c)

d = JsClass('Big', extends='Square')
d.Add(JsMethod('area', T('number'), JsBody([JsText('return super.area() * 2;')])))
f.Add(d)

sw = JsSwitch('n', JsBody([
    JsSwitchCase('0', JsBody([JsText('return "zero";')]), add_break=False),
    JsSwitchCase('1', [JsComment('fall into two'), JsText('n = 2;')]),
    JsSwitchDefault([JsText('return "many";')], add_break=False),
]))
desc = JsFunction('describe', T('string'), JsBody([sw, JsText('return "two";')]), export=True)
desc.AddParameter('n', T('number'))
f.Add(desc)

wait = JsFunction('main', T('Promise<void>'), JsBody([
    JsText('const s = new Square(3);'),
    JsText('assert.equal(s.area(), 9);'),
    JsText('assert.equal(new Big(2).area(), 8);'),
    JsText('console.log(describe(0), describe(1), describe(7), basename(join("a", "b.txt")), Square.count);'),
    JsText(f'console.log({"Color.Green" if ts else "process.argv.length > 0"});'),
    JsBody([JsText('Square.reset();')]),
]), is_async=True)
f.Add(wait)
f.Add(JsText('await main();'))
print(f, end='')
