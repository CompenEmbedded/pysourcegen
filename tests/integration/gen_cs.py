"""Print a C# program that uses every class of the generator."""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'src'))

from pysourcegen import *  # noqa: E402,F403
f = CsFile(namespace='Demo')
f.AddHead(CsComment('Generated by pysourcegen'))
f.AddUsing('System'); f.AddUsing('System.Math', static=True)
e = CsEnum('Color', base='byte')
e.Add(CsDocComment('<summary>Primary</summary>'))
e.AddMember('Red', 1); e.AddMember('Green')
f.Add(e)
i = CsInterface('IShape')
i.Add(CsMethod('Area', 'double', None, modifiers=''))
f.Add(i)
st = CsStruct('Point', modifiers='public readonly')
st.AddProperty('int', 'X', 'get;')
f.Add(st)
c = CsClass('Square', bases=['Base', 'IShape'])
c.Add(CsComment('fields'))
c.AddField('double', '_side', modifiers='private readonly')
c.AddProperty('string', 'Name', value='"square"')
ctor = CsMethod('Square', None, CsBody([CsText('_side = side;')]))
ctor.AddParameter('double', 'side', '1')
c.Add(ctor)
c.Add(CsDocComment('<summary>\nArea.\n</summary>'))
c.Add(CsMethod('Area', 'double', CsBody([CsText('return _side * _side;')])))
c.Add(CsMethod('Nothing', 'void', CsBody([]), modifiers='public static'))
f.Add(CsAttribute('Serializable'))
f.Add(c)
f.Add(CsClass('Base', modifiers='public abstract'))
sw = CsSwitch('c', CsBody([
    CsSwitchCase('Color.Red', [CsText('return "red";')], add_break=False),
    CsSwitchDefault([CsComment('other')]),
]))
p = CsClass('Program', modifiers='public static')
m = CsMethod('Describe', 'string', CsBody([sw, CsText('return Max(1, 2).ToString();')]), modifiers='static')
m.AddParameter('Color', 'c')
p.Add(m)
mn = CsMethod('Main', 'void', CsBody([CsText('Console.WriteLine(new Square(3).Area() + " " + Describe(Color.Red) + " " + Describe(Color.Green));'), CsBody([CsText('Square.Nothing();')])]), modifiers='public static')
p.Add(mn)
f.Add(p)
print(f, end='')
