"""Print a Go program that uses every class of the generator."""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'src'))

from pysourcegen import *  # noqa: E402,F403
f = GoFile('main')
f.AddHead(GoComment('Code generated by pysourcegen. DO NOT EDIT.'))
f.AddImport('fmt'); f.AddImport('strings', 'str'); f.AddImport('errors')
f.Add(GoText('type Color int'))
f.Add(GoText(''))
cb = GoConstBlock()
cb.AddConst('Red', 'Color', 'iota')
cb.AddConst('Green')
cb.AddConst('LightBlue')
f.Add(cb)
cb2 = GoConstBlock()
cb2.AddConst('A', value='1')
cb2.AddConst('Longer', value='22')
cb2.Add(GoComment('separate'))
cb2.AddConst('Typed', 'int', '3')
cb2.AddConst('X', 'string', '"x"')
f.Add(cb2)
vb = GoVarBlock()
vb.AddVar('count', 'int')
vb.AddVar('errBad', value='errors.New("bad")')
f.Add(vb)
s = GoStruct('Point')
s.Add(GoComment('X is the x coordinate'))
s.AddField('X', 'int', 'json:"x"')
s.AddField('YLonger', 'float64', 'json:"y_longer,omitempty"')
s.Add(GoComment('Label after comment'))
s.AddField('Label', 'string')
s.AddField('N', 'int')
s.Add(GoText('fmt.Stringer'))
s.AddField('Z', 'map[string]int', 'json:"z"')
f.Add(s)
f.Add(GoStruct('Empty'))
f.Add(GoInterface('Any'))
i = GoInterface('Shape')
i.Add(GoComment('Area returns the area'))
i.AddMethod('Area() float64')
i.AddMethod('Name() string')
f.Add(i)
m = GoFunction('String', 'string', GoBody([GoText('return fmt.Sprintf("(%d, %v)", p.X, p.YLonger)')]), receiver='p Point')
f.Add(m)
inner = GoSwitch('', [GoSwitchCase('n > 1', [GoText('return "many"')])])
sw = GoSwitch('c', GoBody([
    GoSwitchCase('Red', GoBody([GoText('return "red"')])),
    GoSwitchCase('Green, LightBlue', [GoComment('two'), inner, GoText('return "g"')]),
    GoSwitchDefault([GoText('return str.ToUpper("x")')]),
]))
nm = GoFunction('name', 'string', GoBody([sw]))
nm.AddParameter('c', 'Color'); nm.AddParameter('n', 'int')
f.Add(nm)
f.Add(GoFunction('noop', None, GoBody([])))
mf = GoFunction('pair', '(int, error)', GoBody([GoText('return count, errBad')]))
f.Add(mf)
f.Add(GoFunction('main', None, GoBody([
    GoText('p := Point{X: 1, YLonger: 2}'),
    GoText('fmt.Println(p, name(Green, 2), name(Red, 0), name(5, 0))'),
    GoText('_, err := pair()'),
    GoText('fmt.Println(err, A, Longer, Typed, X, LightBlue)'),
    GoBody([GoText('_ = Empty{}')]),
])))
print(f, end='')
